#!/usr/bin/env python3
"""Write data-raw/colonial_census/CODEBOOK.md from the transcribed CSVs.

For each table in tables.csv: title, pages, number of rows, and every column
with its type and, for coded dimensions, each English code with its printed
French label and frequency. Per-table method and validation details are in
csv/<table>.md.

Usage:  python3 data-raw/colonial_census/codebook.py
"""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
CSV_DIRS = [HERE / "csv", HERE.parent / "yearbook_demography" / "csv",
            HERE.parent / "yearbook_health_education" / "csv",
            HERE.parent / "yearbook_other_chapters" / "csv"]


def find(table):
    for d in CSV_DIRS:
        if (d / f"{table}.csv").exists():
            return d / f"{table}.csv"
    return None


def notes_link(table):
    p = find(table)
    rel = "csv" if p.parent == HERE / "csv" else f"../{p.parent.parent.name}/csv"
    return f"[`{rel}/{table}.md`]({rel}/{table}.md)"
COMMON = {
    "census": "Source volume: `eur1906` (1906 European census), `ind1931` (1931 indigenous census), or the *Statistique générale* edition the value is taken from (`sgt1922` ... `sgt1939`).",
    "gallica_ark": "Gallica ark of the bound volume holding that edition (views are numbered within it).",
    "year": "Year the figure refers to.",
    "table_id": "Table number or letter as printed (`text` for tables printed in the commentary).",
    "source_page": "Printed page number.",
    "gallica_view": "Gallica page view; the scan is at https://gallica.bnf.fr/ark:/12148/<ark>/f<view>.",
    "value": "The printed figure.",
    "flag": "Data-quality flag; see the legend at the top.",
}
GEO = {"controle_civil", "annexe", "caidat", "cheikhat", "locality", "commune"}
SOURCES = {
    "eur1906": "*Dénombrement de la population européenne civile en Tunisie au 16 décembre 1906* "
               "(Tunis, 1907). Source gallica.bnf.fr / Bibliothèques de l'Université de Poitiers, "
               "<https://gallica.bnf.fr/ark:/12148/bd6t53563851>.",
    "ind1931": "*Dénombrement de la population civile indigène (musulmane et israélite) en Tunisie "
               "au 22 mars 1931* (Tunis, 1932). Source gallica.bnf.fr / Bibliothèque nationale de "
               "France, <https://gallica.bnf.fr/ark:/12148/bpt6k994559s>.",
    "sgt": "*Statistique générale de la Tunisie* (Tunis, annual), editions 1922-1930, 1935, 1936 and 1939, "
           "bound in 7 Gallica volumes (see `../yearbook_demography/EDITIONS.md`). Source gallica.bnf.fr / "
           "Ministère des Affaires étrangères.",
}


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def describe(df, col):
    s = df[col]
    if col in COMMON:
        return COMMON[col], None
    if col.endswith("_fr") and col[:-3] in df.columns:
        return f"Printed French label for `{col[:-3]}`.", None
    if col in GEO or col.endswith("_fr"):
        n = s[s != ""].nunique()
        return f"Place or label as printed ({n} distinct values).", None
    if col == "census_year":
        return "Census year the figure refers to.", None
    levels = s.value_counts()
    if len(levels) > 60:
        return f"Text ({len(levels)} distinct values).", None
    fr = f"{col}_fr" if f"{col}_fr" in df.columns else None
    rows = []
    for code, n in levels.sort_index().items():
        label = ""
        if fr:
            labs = df.loc[s == code, fr].unique()
            label = " / ".join(sorted(x for x in labs if x))
        rows.append((code or "(empty)", label, n))
    return "Coded dimension.", rows


def main():
    idx = pd.read_csv(HERE / "tables.csv", dtype=str, keep_default_na=False)
    out = ["# Codebook: 1906 and 1931 colonial census tables", "",
           "Generated by `codebook.py` from the CSVs in `csv/`. Load any table in R with "
           "`load_colonial_census(\"<table>\")`; `colonial_census_tables()` lists them.", "",
           "Every table is tidy: one row per printed cell. Printed subtotals and totals are not "
           "stored, but were used for validation (see each table's notes file, `csv/<table>.md`). "
           "A printed `»` is stored as 0.", "",
           "## Flags", "",
           "| Flag | Meaning |", "|---|---|",
           "| (empty) | Value as printed, read from the OCR or the scan |",
           "| `ocr_corrected` | The OCR misread the value; corrected from the page image |",
           "| `total_mismatch` | Printed value kept, but it does not add up with the printed totals (a misprint in the original) |",
           "| `derived_from_totals` | Cell hidden in the binding; solved exactly from the printed totals and other tables |",
           "| `illegible` | Value could not be read or solved; `value` is NA |",
           "| `not_applicable` | Question not asked of this group; `value` is NA |",
           "| `reprint_corrected` | Taken from another edition's printing, because this one is misprinted or unreadable |",
           "", "## Sources", ""]
    for k, v in SOURCES.items():
        out.append(f"- `{k}`: {v}")
    out += ["", "## Tables", "", "| Table | Printed | Pages | Rows | Values | Title |", "|---|---|---|---:|---|---|"]
    frames = {}
    for _, r in idx.iterrows():
        p = find(r["table"])
        if p is None:
            out.append(f"| `{r['table']}` | {r['table_id']} | {r['pages']} | (pending) | {r['value_type']} | {md_escape(r['title_en'])} |")
            continue
        df = pd.read_csv(p, dtype=str, keep_default_na=False, encoding="utf-8-sig")
        frames[r["table"]] = df
        out.append(f"| [`{r['table']}`](#{r['table']}) | {r['table_id']} | {r['pages']} | {len(df):,} | "
                   f"{r['value_type']} | {md_escape(r['title_en'])} |")
    for _, r in idx.iterrows():
        df = frames.get(r["table"])
        if df is None:
            continue
        flags = df["flag"].replace("", "(empty)").value_counts()
        out += ["", f"### {r['table']}", "",
                f"**{md_escape(r['title_fr'])}**  ", f"*{md_escape(r['title_en'])}*", "",
                f"Source `{r['census']}`, table {r['table_id']}, printed pages {r['pages']}. "
                f"{len(df):,} rows. Value type: {r['value_type']}. "
                f"Flags: " + ", ".join(f"{k} {v:,}" for k, v in flags.items()) + ". "
                f"Notes and validation: {notes_link(r['table'])}.", "",
                "| Column | Description |", "|---|---|"]
        coded = []
        for c in df.columns:
            desc, levels = describe(df, c)
            out.append(f"| `{c}` | {desc} |")
            if levels:
                coded.append((c, levels))
        for c, levels in coded:
            out += ["", f"`{c}`:", "", "| Code | Printed label | N |", "|---|---|---:|"]
            out += [f"| `{md_escape(a)}` | {md_escape(b)} | {n:,} |" for a, b, n in levels]
    (HERE / "CODEBOOK.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"CODEBOOK.md: {len(frames)} tables")


if __name__ == "__main__":
    main()
